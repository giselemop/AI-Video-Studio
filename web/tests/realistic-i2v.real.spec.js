import {expect,test} from '@playwright/test'
import fs from 'node:fs'

const folder='C:/install/AI/Data/RealisticI2V20261022'
test.use({launchOptions:{args:['--disable-gpu','--disable-accelerated-video-decode']}})

test('first completed source can play before the second source is ready',async({page})=>{
  const state=JSON.parse(fs.readFileSync(`${folder}/run.json`,'utf8'))
  test.skip(!state.video20TaskIdPath||state.video30TaskIdPath,'This inspection applies while only the first source is ready')
  await page.goto('http://127.0.0.1:18080/realistic-i2v-compare.html')
  const video=page.locator('#v20')
  await expect.poll(()=>video.evaluate(v=>v.readyState)).toBeGreaterThan(0)
  expect(await video.evaluate(v=>v.controls&&v.muted)).toBe(true)
  await expect(page.getByRole('button',{name:'同步播放',exact:true})).toBeDisabled()
  await video.evaluate(v=>v.play())
  await expect.poll(()=>video.evaluate(v=>v.ended),{timeout:12000}).toBe(true)
  const completion=await video.evaluate(v=>({time:v.currentTime,ended:v.ended,width:v.videoWidth,height:v.videoHeight,decodedFrames:v.getVideoPlaybackQuality().totalVideoFrames,error:v.error?.message||null}))
  expect(completion.width).toBe(1920);expect(completion.height).toBe(1080);expect(completion.decodedFrames).toBeGreaterThan(120);expect(completion.error).toBeNull()
  fs.writeFileSync(`${folder}/browser-first-source.json`,JSON.stringify({status:'Passed',completion,softwareDecode:true},null,2))
})

test('blocked reference run shows four real images and no invented video',async({page})=>{
  const state=JSON.parse(fs.readFileSync(`${folder}/run.json`,'utf8'))
  test.skip(state.stage!=='Blocked','This inspection applies to the recorded content blocker')
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://127.0.0.1:18080/realistic-i2v-compare.html')
  await expect(page.getByRole('status')).toContainText('当前生成受阻，尚未完成新成片')
  await expect(page.locator('#candidates img')).toHaveCount(4)
  await expect.poll(()=>page.locator('#candidates img').evaluateAll(images=>images.every(im=>im.complete&&im.naturalWidth===1536&&im.naturalHeight===864))).toBe(true)
  expect(await page.locator('video').evaluateAll(vs=>vs.every(v=>!v.hasAttribute('src')))).toBe(true)
  await expect(page.getByRole('button',{name:'同步播放',exact:true})).toBeDisabled()
  await expect(page.getByLabel('写实优化10秒成片')).toBeHidden()
  expect(errors).toEqual([])
  await page.screenshot({path:`${folder}/browser-reference-review.png`,fullPage:true})
  fs.writeFileSync(`${folder}/browser-reference-review.json`,JSON.stringify({status:'Passed',images:4,
    dimensions:[1536,864],videoSourceAssigned:false,contentStatus:'Failed',pipelineStatus:'Blocked',pageErrors:errors},null,2))
})

test('actual 20 and 30 step sources seek and play together',async({page})=>{
  const state=JSON.parse(fs.readFileSync(`${folder}/run.json`,'utf8'))
  test.skip(!state.video20TaskIdPath||!state.video30TaskIdPath,'Actual source comparison is not ready')
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://127.0.0.1:18080/realistic-i2v-compare.html')
  await expect(page.getByRole('button',{name:'同步播放',exact:true})).toBeEnabled()
  const sources=page.locator('#v20,#v30')
  const actual=await sources.evaluateAll(vs=>vs.map(v=>({width:v.videoWidth,height:v.videoHeight,duration:v.duration,muted:v.muted})))
  expect(actual.map(v=>[v.width,v.height])).toEqual([[1920,1080],[1920,1080]])
  for(const v of actual){expect(Math.abs(v.duration-124/24)).toBeLessThan(.06);expect(v.muted).toBe(true)}
  await page.getByLabel('源视频对照帧',{exact:true}).fill('48')
  await expect.poll(()=>sources.evaluateAll(vs=>vs.every(v=>!v.seeking))).toBe(true)
  const seeked=await sources.evaluateAll(vs=>vs.map(v=>v.currentTime));for(const t of seeked)expect(Math.abs(t-2)).toBeLessThan(.03)
  await page.getByRole('button',{name:'回到开头',exact:true}).click()
  await page.getByRole('button',{name:'同步播放',exact:true}).click()
  await expect.poll(()=>page.locator('#v20').evaluate(v=>v.ended),{timeout:12000}).toBe(true)
  const completion=await sources.evaluateAll(vs=>vs.map(v=>({time:v.currentTime,paused:v.paused,decoded:v.getVideoPlaybackQuality().totalVideoFrames,error:v.error?.message||null})))
  for(const v of completion){expect(v.time).toBeGreaterThan(5);expect(v.error).toBeNull();expect(v.decoded).toBeGreaterThan(120);expect(v.paused).toBe(true)}
  await page.getByLabel('源视频对照帧',{exact:true}).fill('80')
  await page.getByRole('button',{name:'局部放大',exact:true}).click()
  await expect(page.getByRole('button',{name:'局部放大',exact:true})).toHaveAttribute('aria-pressed','true')
  await page.screenshot({path:`${folder}/browser-comparison-zoom.png`,fullPage:true})
  expect(errors).toEqual([])
  fs.writeFileSync(`${folder}/browser-comparison.json`,JSON.stringify({status:'Passed',actual,seeked,completion,pageErrors:errors},null,2))
})

test('new ten second narration final plays completely with sources paused',async({page})=>{
  test.setTimeout(45000)
  const state=JSON.parse(fs.readFileSync(`${folder}/run.json`,'utf8'))
  test.skip(!state.finalVideoPath,'The actual final assembly is not ready')
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://127.0.0.1:18080/realistic-i2v-compare.html')
  const video=page.getByLabel('写实优化10秒成片',{exact:true})
  await expect.poll(()=>video.evaluate(v=>v.readyState)).toBeGreaterThan(0)
  const actual=await video.evaluate(v=>({width:v.videoWidth,height:v.videoHeight,duration:v.duration,muted:v.muted,volume:v.volume}))
  expect(actual.width).toBe(1920);expect(actual.height).toBe(1080);expect(Math.abs(actual.duration-10)).toBeLessThan(.06)
  expect(actual.muted).toBe(false);expect(actual.volume).toBe(1)
  await page.getByRole('button',{name:'播放完整成片',exact:true}).click()
  await expect.poll(()=>video.evaluate(v=>v.ended),{timeout:20000}).toBe(true)
  const completion=await video.evaluate(v=>({time:v.currentTime,ended:v.ended,decodedFrames:v.getVideoPlaybackQuality().totalVideoFrames,error:v.error?.message||null}))
  expect(completion.time).toBeGreaterThan(9.9);expect(completion.decodedFrames).toBeGreaterThan(230);expect(completion.error).toBeNull()
  expect(await page.locator('#v20,#v30').evaluateAll(vs=>vs.every(v=>v.paused&&v.muted))).toBe(true)
  expect(errors).toEqual([])
  await video.evaluate(v=>{v.currentTime=7.4})
  await expect.poll(()=>video.evaluate(v=>v.seeking)).toBe(false)
  await page.screenshot({path:`${folder}/browser-final.png`,fullPage:true})
  fs.writeFileSync(`${folder}/browser-final-playback.json`,JSON.stringify({status:'Passed',actual,completion,pageErrors:errors},null,2))
})
